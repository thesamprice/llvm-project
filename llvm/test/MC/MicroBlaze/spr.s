# RUN: llvm-mc -triple=microblazeel -show-encoding < %s | FileCheck %s
# REQUIRES: microblaze-registered-target

# MicroBlaze special-purpose register instruction encoding tests (UG984 §5).
# All four instructions share opcode 0x25 (100101); fixed bits in [20:14]
# disambiguate MFS ([15:14]=10), MTS ([15:14]=11), and MSR*SET/CLR ([20]=1).
#
# Latency: 1 cycle for all (UG984 §5 Figs 105-108).
#
# MFS format (Fig 105):
#   [31:26]=0x25  [25:21]=rD  [20]=0  [19]=E  [18:16]=000  [15]=1  [14]=0
#   [13:0]=rS_addr
#
# MTS format (Fig 108):
#   [31:26]=0x25  [25]=0  [24]=E  [23:21]=000  [20:16]=rA  [15]=1  [14]=1
#   [13:0]=rS_addr
#
# MSRSET format (Fig 107):
#   [31:26]=0x25  [25:21]=rD  [20]=1  [19:17]=000  [16]=0  [15]=0  [14:0]=Imm15
#
# MSRCLR format (Fig 106):
#   [31:26]=0x25  [25:21]=rD  [20]=1  [19:17]=000  [16]=1  [15]=0  [14:0]=Imm15

#------------------------------------------------------------------------------
# MFS rD, rS  — move from special register  (E=0, bit[19]=0)
# SPR address 0x0001 = MSR
#
# mfs r3, 1  — rD=r3=3=0b00011, rs=0x0001
#   [31:26]=100101  [25:21]=00011  [20:14]=0,0,0,0,0,1,0
#   [13:0]=00_0000_0000_0001
# Word = 0x25<<26 | 3<<21 | 1<<15 | 1
#      = 0x94000000 | 0x00600000 | 0x00008000 | 0x00000001
#      = 0x94608001
# LE: 01 80 60 94
#------------------------------------------------------------------------------
# CHECK: mfs r3, 1                      # encoding: [0x01,0x80,0x60,0x94]
  mfs r3, 1

# mfs r5, 0  — rD=r5=5, rs=0x0000 (PC)
# Word = 0x94000000 | 5<<21 | 1<<15 | 0
#      = 0x94000000 | 0x00A00000 | 0x00008000 | 0
#      = 0x94A08000
# LE: 00 80 A0 94
# CHECK: mfs r5, 0                      # encoding: [0x00,0x80,0xa0,0x94]
  mfs r5, 0

#------------------------------------------------------------------------------
# MFSE rD, rS — extended MFS  (E=1, bit[19]=1)
# SPR address 0x0003 = EAR (Extended Address Register, extended part)
#
# mfse r3, 3  — rD=r3=3, rs=0x0003, bit[19]=1
# Word = 0x94000000 | 3<<21 | 1<<19 | 1<<15 | 3
#      = 0x94000000 | 0x00600000 | 0x00080000 | 0x00008000 | 0x00000003
#      = 0x94688003
# LE: 03 80 68 94
#------------------------------------------------------------------------------
# CHECK: mfse r3, 3                     # encoding: [0x03,0x80,0x68,0x94]
  mfse r3, 3

#------------------------------------------------------------------------------
# MTS rS, rA  — move to special register  (E=0)
# SPR address 0x0001 = MSR
#
# mts 1, r5  — rs=0x0001, rA=r5=5=0b00101
#   [31:26]=100101  [25:24]=00  [23:21]=000  [20:16]=00101  [15:14]=11
#   [13:0]=00_0000_0000_0001
# Word = 0x25<<26 | 0<<25 | 0<<24 | 5<<16 | 3<<14 | 1
#      = 0x94000000 | 0x00050000 | 0x0000C000 | 0x00000001
#      = 0x9405C001
# LE: 01 C0 05 94
#------------------------------------------------------------------------------
# CHECK: mts 1, r5                      # encoding: [0x01,0xc0,0x05,0x94]
  mts 1, r5

# mts 7, r7  — rs=0x0007 (FSR), rA=r7=7
# Word = 0x94000000 | 7<<16 | 0x0000C000 | 7
#      = 0x94000000 | 0x00070000 | 0x0000C000 | 0x00000007
#      = 0x9407C007
# LE: 07 C0 07 94
# CHECK: mts 7, r7                      # encoding: [0x07,0xc0,0x07,0x94]
  mts 7, r7

#------------------------------------------------------------------------------
# MTSE rS, rA — extended MTS  (E=1, bit[24]=1)
# SPR address 0x1003 = TLBLO (lower physical address)
#
# mtse 0x1003, r5 — rs=0x1003=4099, rA=r5=5, bit[24]=1
# Word = 0x94000000 | 1<<24 | 5<<16 | 3<<14 | 0x1003
#      = 0x94000000 | 0x01000000 | 0x00050000 | 0x0000C000 | 0x00001003
#      = 0x9505D003
# LE: 03 D0 05 95
#------------------------------------------------------------------------------
# CHECK: mtse 4099, r5                  # encoding: [0x03,0xd0,0x05,0x95]
  mtse 4099, r5

#------------------------------------------------------------------------------
# MSRSET rD, imm — read MSR → rD, set bits per imm  (bit[20]=1, bit[16]=0)
# Only available when C_USE_MSR_INSTR=1.
#
# msrset r3, 0  — rD=r3=3, imm=0
# Word = 0x25<<26 | 3<<21 | 1<<20 | 0
#      = 0x94000000 | 0x00600000 | 0x00100000 | 0
#      = 0x94700000
# LE: 00 00 70 94
#------------------------------------------------------------------------------
# CHECK: msrset r3, 0                   # encoding: [0x00,0x00,0x70,0x94]
  msrset r3, 0

# msrset r3, 4  — rD=r3=3, imm=4 (set C bit in MSR)
# imm in bits[14:0]=4; bit[14]=0, bits[13:0]=4
# Word = 0x94700000 | 4 = 0x94700004
# LE: 04 00 70 94
# CHECK: msrset r3, 4                   # encoding: [0x04,0x00,0x70,0x94]
  msrset r3, 4

#------------------------------------------------------------------------------
# MSRCLR rD, imm — read MSR → rD, clear bits per imm  (bit[20]=1, bit[16]=1)
#
# msrclr r3, 0  — rD=r3=3, imm=0
# Word = 0x25<<26 | 3<<21 | 1<<20 | 1<<16 | 0
#      = 0x94000000 | 0x00600000 | 0x00100000 | 0x00010000 | 0
#      = 0x94710000
# LE: 00 00 71 94
#------------------------------------------------------------------------------
# CHECK: msrclr r3, 0                   # encoding: [0x00,0x00,0x71,0x94]
  msrclr r3, 0

# msrclr r3, 4  — rD=r3=3, imm=4 (clear C bit in MSR)
# Word = 0x94710000 | 4 = 0x94710004
# LE: 04 00 71 94
# CHECK: msrclr r3, 4                   # encoding: [0x04,0x00,0x71,0x94]
  msrclr r3, 4
